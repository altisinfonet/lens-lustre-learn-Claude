#!/usr/bin/env node
/**
 * Generates dist/robots.txt and dist/sitemap.xml from the build environment
 * (lane isolation, 2026-08-22).
 *
 * Both were committed with production URLs baked in. Copied unchanged to any
 * other lane they are the most damaging kind of leak in this whole change: a
 * sitemap is an instruction to a crawler, so a staging deploy would have
 * actively submitted production URLs for indexing from a non-production host,
 * and robots.txt would have pointed at the production sitemap.
 *
 * INDEXING POLICY, decided 2026-08-23 (G7). Templating the origin was only the
 * isolation half. The first staging deploy went out crawlable, with a sitemap
 * advertising staging URLs — duplicate content competing with production in
 * search results, which is expensive precisely because search engines keep it.
 *
 * So: THE PRODUCTION LANE IS THE ONLY INDEXABLE LANE. Every other lane emits a
 * blanket `Disallow: /` and advertises no sitemap.
 *
 * ⚠ THIS IS NOT FAIL-CLOSED, and saying so would be a lie worth catching
 * here rather than in a search console. The lane is identified by
 * VITE_SITE_ORIGIN, and lane-config.mjs still defaults that to the production
 * origin when it is unset — so a lane that forgets the variable is classed as
 * production and ships indexable. That residual is deliberately not closed in
 * this file: the same omission would bake production URLs into every asset in
 * the bundle, which is the louder failure, and the guard that catches it is the
 * isolation host check (ISOLATION_EXPECTED_HOST / ISOLATION_FORBIDDEN_HOSTS,
 * rules R7-R10) — which only holds if those are set on every Pages project.
 */
import { writeFileSync, readFileSync, existsSync } from "node:fs";
import { laneDefine, PRODUCTION_SITE_ORIGIN } from "./lane-config.mjs";

const define = laneDefine();
const siteOrigin = JSON.parse(define.__LANE_SITE_ORIGIN__);
const siteHost = JSON.parse(define.__LANE_SITE_HOST__);
const apexHost = JSON.parse(define.__LANE_SITE_APEX_HOST__);

// Canonical URLs have always named the apex where one exists — see
// SITE_DISPLAY_ORIGIN in src/lib/env.ts. Keep production byte-identical.
const displayOrigin = `https://${apexHost || siteHost}`;

if (!existsSync("dist")) {
  console.error("generate-seo-assets FAIL: dist/ missing — run the build first.");
  process.exit(1);
}

// Production is a DOMAIN, not one spelling of it. The apex and the www host
// are the same site — the apex redirects to www — so both must count as
// production. Comparing siteOrigin to PRODUCTION_SITE_ORIGIN by equality would
// have classed VITE_SITE_ORIGIN=https://50mmretina.com as non-production and
// shipped `Disallow: /` to the live site. The asymmetry decides the direction
// of doubt: wrongly de-indexing production is expensive and slow to undo,
// while a non-production lane deliberately named under the production apex is
// not a thing anyone builds.
const PRODUCTION_HOST = PRODUCTION_SITE_ORIGIN.replace(/^https?:\/\//, "").replace(/^www\./, "");
const isProduction = siteHost.replace(/^www\./, "") === PRODUCTION_HOST;

if (!isProduction) {
  // No sitemap reference: advertising one to a crawler that has been told to
  // stay out is a mixed signal, and some crawlers honour the sitemap anyway.
  const blocked =
    "# NON-PRODUCTION LANE — NOT FOR INDEXING.\n" +
    `# Lane origin: ${siteOrigin}\n` +
    "# Generated by scripts/generate-seo-assets.mjs. The production lane is the\n" +
    "# only indexable lane; see the header of that file for why.\n" +
    "\nUser-agent: *\nDisallow: /\n";
  writeFileSync("dist/robots.txt", blocked);
  // A sitemap is still written so the path does not 404, but it lists nothing.
  writeFileSync(
    "dist/sitemap.xml",
    '<?xml version="1.0" encoding="UTF-8"?>\n' +
      '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"></urlset>\n',
  );
  console.log(`generate-seo-assets OK: non-production lane ${siteOrigin} — robots.txt blocks all crawling, sitemap.xml empty.`);
  process.exit(0);
}

let written = 0;
for (const file of ["robots.txt", "sitemap.xml"]) {
  const template = `public/${file}`;
  if (!existsSync(template)) {
    console.error(`generate-seo-assets FAIL: ${template} missing.`);
    process.exit(1);
  }
  const out = readFileSync(template, "utf8")
    .replaceAll("__SITE_ORIGIN__", displayOrigin)
    .replaceAll("__SITE_HOST__", apexHost || siteHost);

  const leftover = out.match(/__[A-Z_]+__/g);
  if (leftover) {
    console.error(
      `generate-seo-assets FAIL: unsubstituted placeholder(s) in ${file}: ${[...new Set(leftover)].join(", ")}`,
    );
    process.exit(1);
  }
  writeFileSync(`dist/${file}`, out);
  written++;
}

// A sitemap that still names another lane is the failure this script exists to
// prevent; refusing here beats discovering it in a search console.
const sitemap = readFileSync("dist/sitemap.xml", "utf8");
const strayOrigins = [...new Set(sitemap.match(/https?:\/\/[a-z0-9.-]+/gi) || [])].filter(
  (u) => !u.startsWith(displayOrigin) && !u.includes("sitemaps.org"),
);
if (strayOrigins.length) {
  console.error(`generate-seo-assets FAIL: sitemap names other origins: ${strayOrigins.join(", ")}`);
  process.exit(1);
}

console.log(`generate-seo-assets OK: ${written} files; origin=${displayOrigin}`);
