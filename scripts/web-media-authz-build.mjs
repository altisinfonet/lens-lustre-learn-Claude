#!/usr/bin/env node
/**
 * Builds cloudflare/media-authz/worker.js — the ONE file the Owner pastes into
 * the Cloudflare dashboard (the same deploy method as seo-edge-injector).
 * Sources: cloudflare/media-authz/{worker,handler}.ts + the shared
 * src/lib/video/shared/{playToken,rules}.ts the Pages minter also uses.
 *
 *   node scripts/web-media-authz-build.mjs          write worker.js
 *   node scripts/web-media-authz-build.mjs --check  exit 1 if worker.js differs
 *                                                   from a fresh build (CI)
 * esbuild comes from the lockfile (vite's dependency); no package.json change.
 */
import { build } from "esbuild";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "cloudflare/media-authz/worker.js");
const header =
  "// GENERATED by scripts/web-media-authz-build.mjs from cloudflare/media-authz/*.ts and\n" +
  "// src/lib/video/shared/{playToken,rules}.ts. Do not edit; paste this whole file into the\n" +
  "// Cloudflare dashboard (cloudflare/media-authz/README.md). CI fails if it is stale.\n";

const res = await build({
  entryPoints: [join(root, "cloudflare/media-authz/worker.ts")],
  bundle: true, format: "esm", target: "es2022", platform: "neutral",
  write: false, legalComments: "none", charset: "utf8", logLevel: "silent",
});
const js = header + res.outputFiles[0].text;

if (process.argv.includes("--check")) {
  const have = existsSync(out) ? readFileSync(out, "utf8") : "";
  if (have !== js) {
    console.error("✗ cloudflare/media-authz/worker.js is stale — run: node scripts/web-media-authz-build.mjs");
    process.exit(1);
  }
  console.log(`✓ worker.js matches its sources (${Buffer.byteLength(js)} bytes)`);
} else {
  writeFileSync(out, js);
  console.log(`wrote cloudflare/media-authz/worker.js (${Buffer.byteLength(js)} bytes)`);
}
