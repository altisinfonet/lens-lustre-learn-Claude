/** Every key the generator produces, exactly as the client sends it (bucket first). */
function generatedKeys(): string[] {
  const out: string[] = [];
  for (const type of Object.keys(BUCKET_FOR) as ImagePathType[]) {
    for (const ext of ["webp", "jpg", "PNG", "pdf"]) {
      const subPath = type === "my-photo" ? ALBUM : type === "certificate-template" ? "certificate_logo" : undefined;
      out.push(`${BUCKET_FOR[type]}/${generateImagePath({ userId: UID, type, ext, subPath })}`);
    }
  }
  // Posts: the dimension suffix, the ladder marker, each rung, the thumbnail —
  // built the way uploadImageWithThumbnail builds them.
  const base = `post-images/${generateImagePath({ userId: UID, type: "post", ext: "webp" })}`;
  const full = base.replace(/\.webp$/, `${dimsSuffix(1620, 1080)}${LADDER_MARKER}.webp`);
  out.push(full, full.replace(".webp", "-thumb.webp"));
  for (const rung of LADDER_RUNGS) out.push(rungPath(full, rung));
  const unmarked = base.replace(/\.webp$/, `${dimsSuffix(1080, 1350)}.webp`);
  out.push(unmarked, unmarked.replace(".webp", "-thumb.webp"));
  return out;
}

