describe("storageObjectUrl addresses exactly the checked key", () => {
  it("path-style endpoint (R2): /<bucket>/<key>, for every real key", () => {
    for (const key of LEGIT) {
      const url = storageObjectUrl(R2, key);
      expect(url).toBe(`${R2.endpoint}/${R2.bucket_name}/${key}`);
      expect(new URL(url).pathname).toBe(`/${R2.bucket_name}/${key}`);
    }
  });

  it("virtual-host style (no endpoint): /<key>", () => {
    for (const key of LEGIT) {
      const url = storageObjectUrl(AWS, key);
      expect(url).toBe(`https://${AWS.bucket_name}.s3.${AWS.region}.amazonaws.com/${key}`);
      expect(new URL(url).pathname).toBe(`/${key}`);
    }
  });

  it("an endpoint with a trailing slash or its own base path still lines up", () => {
    expect(new URL(storageObjectUrl({ ...R2, endpoint: `${R2.endpoint}/` }, "a/b.webp")).pathname).toBe(
      `/${R2.bucket_name}/a/b.webp`,
    );
    expect(new URL(storageObjectUrl({ ...R2, endpoint: "https://minio.example.com/storage/" }, "a/b.webp")).pathname).toBe(
      `/storage/${R2.bucket_name}/a/b.webp`,
    );
  });

  it("the parser really does resolve these forms — which is why the grammar refuses them", () => {
    // Plain WHATWG URL behaviour, shown so the refusals above are not taken on
    // faith: each of these keys would be requested as a DIFFERENT path.
    const base = `${R2.endpoint}/${R2.bucket_name}`;
    for (const key of ["a/../b", "a/./b", "a/%2e%2e/b", "a/.%2e/b", "a/%2E./b"]) {
      expect(new URL(`${base}/${key}`).pathname).not.toBe(`/${R2.bucket_name}/${key}`);
      expect(validateStorageKey(key)).toBeNull();
    }
  });

  it("refuses, rather than returns, a URL for a key the parser would re-read", () => {
    for (const key of ["a/../b", "a/./b", "../a", "a/..", "./a", "a/.", "..", "."]) {
      expect(() => storageObjectUrl(R2, key), key).toThrow(/storage key refused/);
      expect(() => storageObjectUrl(AWS, key), key).toThrow(/storage key refused/);
    }
  });

  it("percent signs and URL syntax are encoded, so a direct caller still gets the literal key", () => {
    // Belt and braces for callers that handle legacy keys without the strict
    // grammar (the shared read/copy helpers): nothing in the key acts as syntax.
    const url = storageObjectUrl(R2, "a/%2e%2e/b?c#d");
    expect(new URL(url).pathname).toBe(`/${R2.bucket_name}/a/%252e%252e/b%3Fc%23d`);
    expect(new URL(url).search).toBe("");
    expect(new URL(url).hash).toBe("");
  });

  it("refuses a bucket name the parser would re-read, and an empty key", () => {
    expect(() => storageObjectUrl({ ...R2, bucket_name: ".." }, "a/b")).toThrow(/storage key refused/);
    expect(() => storageObjectUrl({ ...R2, bucket_name: "a b" }, "a/b")).toThrow(/storage key refused/);
    expect(() => storageObjectUrl(R2, "")).toThrow(/storage key refused/);
  });

  it("never echoes the key in its error (it carries a member id)", () => {
    try {
      storageObjectUrl(R2, `avatars/${UID}/./avatar.webp`);
      throw new Error("expected a refusal");
    } catch (e) {
      expect(String((e as Error).message)).not.toContain(UID);
    }
  });
});

