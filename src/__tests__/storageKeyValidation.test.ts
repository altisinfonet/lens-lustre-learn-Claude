describe("storageSafeFileName / storageSafeExtension keep client keys inside the grammar", () => {
  it("story and highlight keys built from any file name validate", () => {
    for (const name of NASTY_NAMES) {
      for (const folder of ["stories", "highlights"]) {
        const key = `avatars/${UID}/${folder}/${TS}-${storageSafeFileName(name, "story")}`;
        expect(validateStorageKey(key), JSON.stringify(name)).toBe(key);
      }
    }
  });

  it("extension-derived keys validate for any file name", () => {
    for (const name of NASTY_NAMES) {
      const key = `support-attachments/${UID}/${TS}-${RAND}.${storageSafeExtension(name, "bin")}`;
      expect(validateStorageKey(key), JSON.stringify(name)).toBe(key);
    }
  });

  it("ordinary names pass through unchanged", () => {
    for (const name of ["IMG_20241012_101010.webp", "IMG_0001.HEIC", "photo-1.jpg", "PXL_20241012_101010123.webp"]) {
      expect(storageSafeFileName(name)).toBe(name);
    }
  });

  it("awkward names are reduced, not refused", () => {
    expect(storageSafeFileName("WhatsApp Image 2024-10-12 at 10.10.10.webp")).toBe("WhatsApp-Image-2024-10-12-at-10.10.10.webp");
    expect(storageSafeFileName("photo (1).webp")).toBe("photo-1.webp");
    expect(storageSafeFileName("café crème.webp")).toBe("cafe-creme.webp");
    expect(storageSafeFileName("写真.webp", "story")).toBe("story.webp");
    expect(storageSafeFileName("", "story")).toBe("story");
    expect(storageSafeFileName("..webp", "story")).toBe("story.webp");
  });

  it("an extension is kept only when it is a plain one", () => {
    expect(storageSafeExtension("report.PDF", "bin")).toBe("PDF");
    expect(storageSafeExtension("archive.tar.gz", "bin")).toBe("gz");
    // `name.split(".").pop()` returned the whole name here.
    expect(storageSafeExtension("scan from phone", "bin")).toBe("bin");
    expect(storageSafeExtension(".profile", "bin")).toBe("bin");
    expect(storageSafeExtension("x.verylongextension", "bin")).toBe("bin");
    expect(storageSafeExtension("x.jp g", "png")).toBe("png");
  });

  it("the call sites that put a member's file name into a key use the helpers", () => {
    const read = (p: string) => readFileSync(join(ROOT, p), "utf8").replace(/\r\n/g, "\n");
    for (const p of ["src/components/feed/FeedStoriesBar.tsx", "src/components/profile/ProfileStories.tsx"]) {
      const src = read(p);
      expect(src, `${p} interpolates a raw file name into a storage key`).not.toMatch(/\$\{compressed\.name\}/);
      expect(src).toMatch(/storageSafeFileName\(compressed\.name/);
    }
    for (const p of [
      "src/pages/HelpSupport.tsx",
      "src/components/admin/AdminSupportTickets.tsx",
      "src/components/admin/AdminJudgingTags.tsx",
      "src/components/FileUploadDropZone.tsx",
    ]) {
      const src = read(p);
      expect(src, `${p} derives a key extension without storageSafeExtension`).toMatch(
        /const ext = storageSafeExtension\(file\.name, "\w+"\);/,
      );
      expect(src).not.toMatch(/const ext = file\.name\.split\("\."\)\.pop\(\) \|\| "/);
    }
  });
});
