const ROOT = process.cwd();
const FN_DIR = join(ROOT, "supabase", "functions");

/** Comments removed (as deletionProtocol.test.ts does) and CRLF normalised. */
const strip = (s: string) =>
  s.replace(/\r\n/g, "\n").replace(/\/\*[\s\S]*?\*\//g, " ").replace(/(^|[^:])\/\/.*$/gm, "$1");

const fnSource = (name: string) => strip(readFileSync(join(FN_DIR, name, "index.ts"), "utf8"));

function at(src: string, pattern: RegExp, what: string): number {
  const m = pattern.exec(src);
  expect(m, `${what} — not found`).not.toBeNull();
  return m ? m.index : -1;
}

const SHARED_IMPORT =
  /import\s*\{[^}]*\bvalidateStorageKey\b[^}]*\}\s*from\s*["']\.\.\/_shared\/s3\.ts["']/;

describe("the four caller-facing storage functions validate, then authorise, then sign", () => {
  for (const name of ["s3-delete", "s3-upload", "s3-presign-upload", "s3-signed-url"]) {
    describe(name, () => {
      const src = fnSource(name);

      it("imports the shared validator and URL builder", () => {
        expect(src).toMatch(SHARED_IMPORT);
        for (const helper of ["storageKeyWithPrefix", "storageObjectUrl"]) {
          expect(src, `${name} does not import ${helper}`).toMatch(
            new RegExp(`import\\s*\\{[^}]*\\b${helper}\\b[^}]*\\}\\s*from\\s*["']\\.\\.\\/_shared\\/s3\\.ts["']`),
          );
        }
      });

      it("builds no request URL by hand from the raw key", () => {
        expect(src, "a `${baseUrl}/${…}` URL is back — it does not go through storageObjectUrl").not.toMatch(
          /\$\{baseUrl\}\/\$\{/,
        );
        expect(src, "the old deny-list is back in place of the validator").not.toMatch(/\.includes\(\s*["']\.\.["']\s*\)/);
      });

      it("the signed key is the prefix joined to the VALIDATED path", () => {
        expect(src).toMatch(/storageKeyWithPrefix\(s3\.path_prefix,\s*filePath\)/);
        expect(src).toMatch(/storageObjectUrl\(s3,\s*s3Key\)/);
      });
    });
  }

  it("s3-delete: every entry is validated before the ownership gate, and both before any request", () => {
    const src = fnSource("s3-delete");
    const validate = at(src, /const filePath = validateStorageKey\(rawPath\)/, "per-entry validation");
    const gate = at(src, /isPathAllowed\(filePath,/, "ownership gate on the validated key");
    const build = at(src, /storageObjectUrl\(s3, s3Key\)/, "URL proof");
    const send = at(src, /await fetch\(url,/, "the DELETE request");
    expect(validate).toBeLessThan(gate);
    expect(gate).toBeLessThan(build);
    expect(build).toBeLessThan(send);
    // The ownership gate is never handed anything but the validated key.
    expect(src.match(/isPathAllowed\((\w+)/g)?.filter((c) => !/isPathAllowed\((key|filePath)\b/.test(c))).toEqual([]);
    // The signature covers the proven path.
    expect(src).toMatch(/const target = new URL\(url\)/);
    expect(src).toMatch(/"DELETE",\s*target\.pathname/);
  });

  it("s3-upload: validates the form field before the ownership gate and signs the proven path", () => {
    const src = fnSource("s3-upload");
    const validate = at(src, /const filePath = validateStorageKey\(rawPath\)/, "validation");
    const gate = at(src, /isPathAllowed\(filePath,/, "ownership gate on the validated key");
    const build = at(src, /const url = storageObjectUrl\(s3, s3Key\)/, "URL proof");
    const send = at(src, /await fetch\(url,/, "the PUT request");
    expect(validate).toBeLessThan(gate);
    expect(gate).toBeLessThan(build);
    expect(build).toBeLessThan(send);
    expect(src).toMatch(/const canonicalUri = target\.pathname/);
  });

  it("s3-presign-upload: validates path AND pair.path before the ownership gate; presigns the proven path", () => {
    const src = fnSource("s3-presign-upload");
    const validate = at(src, /const filePath = validateStorageKey\(rawPath\)/, "path validation");
    const validatePair = at(src, /const validPairPath = validateStorageKey\(rawPairPath\)/, "pair.path validation");
    at(src, /pairPath = validPairPath;/, "pair path is the validated one");
    const gate = at(src, /isPathAllowed\(filePath,/, "ownership gate on the validated key");
    const gatePair = at(src, /isPathAllowed\(pairPath,/, "ownership gate on the validated pair key");
    expect(validate).toBeLessThan(gate);
    expect(validatePair).toBeLessThan(gatePair);
    expect(src).toMatch(/storageKeyWithPrefix\(s3\.path_prefix,\s*pairPath\)/);
    expect(src).toMatch(/const objectUrl = storageObjectUrl\(s3, s3Key\)/);
    expect(src).toMatch(/const uploadUrl = `\$\{objectUrl\}\?/);
    expect(src).toMatch(/"PUT",\s*fullUrl\.pathname/);
  });

  it("s3-signed-url: validates before the bucket allow-list and the ownership check; presigns the proven path", () => {
    const src = fnSource("s3-signed-url");
    const validate = at(src, /const filePath = validateStorageKey\(rawPath\)/, "validation");
    const allow = at(src, /ALLOWED_PREFIXES\.some\(\(p\) => filePath\.startsWith\(p\)\)/, "bucket allow-list on the validated key");
    const owner = at(src, /const pathParts = filePath\.split\("\/"\)/, "ownership check on the validated key");
    expect(validate).toBeLessThan(allow);
    expect(allow).toBeLessThan(owner);
    expect(src).toMatch(/const objectUrl = storageObjectUrl\(s3, s3Key\)/);
    expect(src).toMatch(/const canonicalUri = target\.pathname/);
    expect(src).toMatch(/const presignedUrl = `\$\{objectUrl\}\?/);
  });
});

