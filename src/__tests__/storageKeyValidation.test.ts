describe("path_prefix is held to the same grammar", () => {
  it("no prefix, or an empty one, means the key is the path", () => {
    for (const none of [undefined, null, "", "/", "//"]) {
      expect(normalisedPathPrefix(none)).toBe("");
      expect(storageKeyWithPrefix(none, `avatars/${UID}/avatar.webp`)).toBe(`avatars/${UID}/avatar.webp`);
    }
  });

  it("a valid prefix is joined with one slash, trailing slashes dropped", () => {
    expect(storageKeyWithPrefix("uploads/50mm-retina", "post-images/x.webp")).toBe("uploads/50mm-retina/post-images/x.webp");
    expect(storageKeyWithPrefix("uploads/50mm-retina///", "post-images/x.webp")).toBe("uploads/50mm-retina/post-images/x.webp");
  });

  it("an invalid prefix refuses every key rather than signing an unchecked one", () => {
    for (const bad of ["/uploads", "uploads/../x", "up loads", "a//b", "%2e%2e", 7, {}]) {
      expect(normalisedPathPrefix(bad)).toBeNull();
      expect(storageKeyWithPrefix(bad, "post-images/x.webp")).toBeNull();
    }
  });

  it("an invalid path is refused whatever the prefix", () => {
    expect(storageKeyWithPrefix("uploads", "a/../b")).toBeNull();
    expect(storageKeyWithPrefix("", "a/%2e%2e/b")).toBeNull();
  });
});

