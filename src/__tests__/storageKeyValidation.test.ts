/**
 * ─────────────────────────────────────────────────────────────────────────────
 * THE KEY THAT IS CHECKED IS THE KEY THAT IS SIGNED.
 *
 * The storage edge functions take a caller-named key, run an ownership check
 * on it, and sign a request for it. A URL parser does not treat a path as an
 * opaque string — it resolves dot-segments (also when percent-encoded), reads
 * "\" as "/" and stops the path at "?" or "#" — so a key is only safe to check
 * and sign if nothing in it can be re-read that way.
 *
 * Three things are pinned here:
 *   1. validateStorageKey (supabase/functions/_shared/s3.ts) accepts every key
 *      shape the app really writes — generated by the app's own path builders
 *      wherever one exists — and refuses everything outside the grammar.
 *   2. storageObjectUrl proves that the URL it returns addresses exactly
 *      "<bucket path>/<key>", and refuses rather than returns otherwise.
 *   3. Every function that signs a single-object request validates FIRST,
 *      authorises the validated key, and signs a URL built from that key —
 *      asserted on the source, so an edit that drops a step fails here.
 *
 * The shared module has no imports of its own and reads nothing from Deno at
 * import time, so importing it into this web test program is free (the same
 * reasoning as storageLane.test.ts).
 * ─────────────────────────────────────────────────────────────────────────────
 */
