-- ═══════════════════════════════════════════════════════════════════════════
-- 20261013_0002 — staging: restore the two auth.users triggers production has
-- Lane: STAGING ONLY (fpszggreishhuvdpkmdr). Refuses any other lane.
-- D1 (Database & Runtime), 2026-10-13. Code only until applied through
-- apply-migration.yml with target=staging.
-- ═══════════════════════════════════════════════════════════════════════════
--
-- WHY. Production carries two user triggers on auth.users; staging carries
-- none. Without them a new sign-up on staging gets an auth.users row and no
-- profiles row, so sign-up cannot be tested on staging at all.
--   production (read-only collector, 2026-10-13 06:51Z,
--   _control/forensic/supabase-20261013-121953/live/db/triggers.json,
--   not in this repo; both enabled = 'O'):
--     CREATE TRIGGER on_auth_user_created AFTER INSERT ON auth.users FOR EACH ROW EXECUTE FUNCTION handle_new_user()
--     CREATE TRIGGER on_auth_user_login_sync AFTER UPDATE ON auth.users FOR EACH ROW EXECUTE FUNCTION sync_oauth_on_login()
--   staging (read-only SELECTs, 2026-10-13, after 20261013_0001): no
--   non-internal trigger on auth.users; 50 users, 50 profiles.
--
-- HOW STAGING LOST THEM. The repository creates both triggers
-- (20260224160300 / 20260224163635: on_auth_user_created; 20260325112938:
-- on_auth_user_login_sync), and the old staging project had the first one —
-- 20260910_00095 inserts into auth.users precisely because "the trigger
-- on_auth_user_created -> handle_new_user() is what really runs at signup".
-- The current staging project was built on 2026-09-11 by apply-migration.yml
-- run #54 from a one-time bootstrap (now
-- UNAPPLIED_20260911101721_new_project_full_schema_bootstrap.sql, withdrawn
-- under R-24) whose own header says it is the "full PUBLIC schema DDL",
-- generated by catalog introspection of the public schema. Its 152 CREATE
-- TRIGGER statements are all on public tables; a trigger that lives on
-- auth.users was outside what it read, so it was never carried across.
--
-- WHAT THIS FILE DOES — and nothing else:
--   creates on_auth_user_created and on_auth_user_login_sync on auth.users,
--   each exactly as production defines it (checked with pg_get_triggerdef
--   below). No function, grant, policy or row is changed. CREATE TRIGGER does
--   not fire for rows that already exist, so the 50 seeded users and their
--   profiles are not touched by applying it.
--
-- THE FUNCTIONS THE TRIGGERS CALL ARE ALREADY PRODUCTION'S. public.handle_new_user()
-- and public.sync_oauth_on_login() on staging equal production's dump:
-- md5(prosrc) ca4a770bff3c438515f6edf9b977efbb / 6c157691677358931ff05084c7fefee4,
-- SECURITY DEFINER, search_path=public, plpgsql, owner postgres, same ACL.
-- PRE-002 refuses unless that is still true at apply time, so a trigger is
-- never attached to a body that differs from production's.
--
-- WHAT A STAGING SIGN-UP DOES ONCE THIS IS APPLIED (same chain as production;
-- staging read 2026-10-13):
--   handle_new_user -> INSERT profiles (name from metadata, fallback avatar)
--     BEFORE triggers: reserved-handle check, picture, name normalising,
--       custom_url assignment, empty-name validation
--     AFTER triggers: profiles_public_data row; auto-follow of the official
--       account (follows -> profile_stats counts, and a 'new_follower'
--       user_notifications row FOR THE OFFICIAL ACCOUNT); newsletter row
--       (source 'registration', a row only, nothing is sent); first-admin
--       check (staging already has its admin, so it does nothing);
--       custom_url_history row (staging-only trigger, not on production)
--   -> INSERT user_roles ('user') -> db_audit_logs row.
--   The 'new_follower' notification then runs send_notification_email
--   (enqueues to pgmq transactional_emails) and push_on_notification
--   (net.http_post to push_config.function_url). Neither is created or
--   changed here. As read on staging 2026-10-13:
--   * EMAIL — nothing is sent. The transactional queue has no worker wired
--     (no p9_cron_http:process-email-queue secret, so email_queue_wake
--     returns 'no target'; no drain cron job). It holds 51 messages, enqueued
--     2026-09-11 14:42Z -> 2026-09-14 14:24Z: 49 'New Follower' to the official
--     account at @example.invalid and 2 'New Badge!' to one @staging.test
--     address — reserved TLDs, undeliverable even if a drainer were wired.
--     Staging has no auth_emails queue at all (so no p9_email_wake on one).
--   * PUSH — push_config.function_url named PRODUCTION's send-push
--     (jtdtehuqtinjxropkkcn): pre-existing cross-lane wiring, repointed by a
--     separate unit. PRE-005 refuses this file until that repoint has landed,
--     so a staging sign-up can never reach production through this path.
--   sync_oauth_on_login: returns at once unless last_sign_in_at changed; on a
--   login it only fills a NULL full_name (or re-asserts the admin brand name).
--   For the 50 existing staging users it updates no row (0 NULL names; the
--   admin already carries the brand name).
--
-- OWNERSHIP (Supabase). auth.users is owned by supabase_auth_admin, not by the
-- migration role (postgres, not superuser, not a member of the owner). CREATE
-- TRIGGER needs the TRIGGER privilege on the table plus EXECUTE on the
-- function — measured on staging 2026-10-13: postgres holds TRIGGER on
-- auth.users (relacl postgres=ar*wdDxtm/supabase_auth_admin) and owns both
-- functions. PRE-001 re-checks it. That is proven from the catalog, not yet by
-- execution on Supabase; the PROBE pass after the apply closes it. DROP TRIGGER
-- would need ownership; the rollback relies on supautils.drop_trigger_grants,
-- which lists postgres for auth.users on staging (measured the same day) —
-- likewise unproven until the rollback is ever run.
--
-- LOCK. CREATE TRIGGER takes SHARE ROW EXCLUSIVE on auth.users, which waits
-- for in-flight sign-ins/logins and makes new ones wait behind it.
-- lock_timeout 5s bounds that; on timeout nothing is applied — re-dispatch.
-- PostgREST's ddl watch sends one schema-cache reload on CREATE TRIGGER.
--
-- ORDERING (PRE-005). Apply only AFTER staging's public.push_config.function_url
-- is NULL or names staging's own project (https://fpszggreishhuvdpkmdr.supabase.co/…).
-- Until then every staging sign-up would POST a 'new_follower' push to
-- production's send-push. PRE-005 reads the column (read-only) and refuses;
-- its message names only the host, never the URL's path or query.
--
-- RE-RUN: idempotent. A trigger already present with production's exact
-- definition is left alone; one present under either name with ANY other
-- definition, or any other user trigger on auth.users, is refused (PRE-003,
-- PRE-004) — never replaced or dropped by this file.
-- ROLLBACK: supabase/rollback/20261013_0002_staging_auth_user_triggers_ROLLBACK.sql
-- PROBE:    supabase/migrations/PROBE_20261013_0002_staging_auth_user_triggers.sql
-- ═══════════════════════════════════════════════════════════════════════════

BEGIN;

DO $lane_guard$
BEGIN
  IF coalesce(current_setting('p32.lane', true), '') <> 'staging' THEN
    RAISE EXCEPTION
      'APPLY REFUSED — this file is for STAGING only and p32.lane reads %. '
      'Dispatch apply-migration.yml with target=staging (it sets p32.lane = ''staging'').',
      coalesce(current_setting('p32.lane', true), '(unset)')
    USING ERRCODE = 'raise_exception';
  END IF;
END
$lane_guard$;

SET LOCAL lock_timeout = '5s';
-- pg_get_triggerdef() schema-qualifies the function name only when it is not
-- visible on the search_path. Production's text names it unqualified with
-- public on the path; pin the path so the comparisons below are deterministic.
-- (Every DDL statement in this file names its objects schema-qualified.)
SET LOCAL search_path TO public;

DO $preconditions$
DECLARE
  r    record;
  _bad text := '';
BEGIN
  -- PRE-001 · auth.users exists and the migration role holds TRIGGER on it.
  IF to_regclass('auth.users') IS NULL THEN
    RAISE EXCEPTION 'AUTHTRG-0002-PRE-001: auth.users does not exist' USING ERRCODE = 'raise_exception';
  END IF;
  IF NOT has_table_privilege(current_user, 'auth.users', 'TRIGGER') THEN
    RAISE EXCEPTION 'AUTHTRG-0002-PRE-001: % lacks the TRIGGER privilege on auth.users (owner %) — CREATE TRIGGER would be refused',
      current_user, (SELECT c.relowner::regrole::text FROM pg_class c WHERE c.oid = 'auth.users'::regclass)
    USING ERRCODE = 'raise_exception';
  END IF;

  -- PRE-002 · both trigger functions are production's, and current_user may EXECUTE them.
  FOR r IN
    SELECT v.fn, v.want_md5, p.oid AS fn_oid, md5(p.prosrc) AS got_md5, p.prosecdef,
           p.proconfig::text AS cfg, p.prorettype::regtype::text AS rettype, l.lanname,
           p.proowner::regrole::text AS owner
      -- (hash listed first: the gitleaks generic-api-key rule takes a name that
      --  contains the word auth followed by a hex literal for a credential)
      FROM (VALUES
        ('ca4a770bff3c438515f6edf9b977efbb', 'handle_new_user'),
        ('6c157691677358931ff05084c7fefee4', 'sync_oauth_on_login')
      ) AS v(want_md5, fn)
      LEFT JOIN pg_proc p
        ON p.pronamespace = 'public'::regnamespace AND p.proname::text = v.fn AND p.pronargs = 0
      LEFT JOIN pg_language l ON l.oid = p.prolang
  LOOP
    IF r.fn_oid IS NULL THEN
      _bad := _bad || E'\n  PRE-002 public.' || r.fn || '() does not exist';
    ELSIF r.got_md5 IS DISTINCT FROM r.want_md5
       OR r.prosecdef IS DISTINCT FROM true
       OR r.cfg IS DISTINCT FROM '{search_path=public}'
       OR r.rettype IS DISTINCT FROM 'trigger'
       OR r.lanname IS DISTINCT FROM 'plpgsql'
       OR r.owner IS DISTINCT FROM 'postgres' THEN
      _bad := _bad || E'\n  PRE-002 public.' || r.fn || '() is not production''s (md5 ' || coalesce(r.got_md5, '?')
                   || ', definer ' || coalesce(r.prosecdef::text, '?') || ', config ' || coalesce(r.cfg, 'NULL')
                   || ', returns ' || coalesce(r.rettype, '?') || ', ' || coalesce(r.lanname, '?')
                   || ', owner ' || coalesce(r.owner, '?') || ')';
    ELSIF NOT has_function_privilege(current_user, r.fn_oid, 'EXECUTE') THEN
      _bad := _bad || E'\n  PRE-002 ' || current_user || ' lacks EXECUTE on public.' || r.fn || '()';
    END IF;
  END LOOP;

  -- PRE-003 · a trigger already present under either name must be production's exactly.
  FOR r IN
    SELECT t.tgname::text AS name, pg_get_triggerdef(t.oid) AS got_def, t.tgenabled::text AS got_enabled, w.want_def
      FROM pg_trigger t
      JOIN (VALUES
        ('on_auth_user_created',
         'CREATE TRIGGER on_auth_user_created AFTER INSERT ON auth.users FOR EACH ROW EXECUTE FUNCTION handle_new_user()'),
        ('on_auth_user_login_sync',
         'CREATE TRIGGER on_auth_user_login_sync AFTER UPDATE ON auth.users FOR EACH ROW EXECUTE FUNCTION sync_oauth_on_login()')
      ) AS w(name, want_def) ON w.name = t.tgname::text
     WHERE t.tgrelid = 'auth.users'::regclass
  LOOP
    IF r.got_def IS DISTINCT FROM r.want_def OR r.got_enabled IS DISTINCT FROM 'O' THEN
      _bad := _bad || E'\n  PRE-003 ' || r.name || ' already exists and differs from production: '
                   || r.got_def || ' (enabled ' || r.got_enabled || ')';
    END IF;
  END LOOP;

  -- PRE-004 · no other user trigger on auth.users (production has exactly these two).
  FOR r IN
    SELECT t.tgname::text AS name, pg_get_triggerdef(t.oid) AS def
      FROM pg_trigger t
     WHERE t.tgrelid = 'auth.users'::regclass
       AND NOT t.tgisinternal
       AND t.tgname::text NOT IN ('on_auth_user_created', 'on_auth_user_login_sync')
  LOOP
    _bad := _bad || E'\n  PRE-004 unexpected user trigger on auth.users: ' || r.def;
  END LOOP;

  -- PRE-005 · ordering: staging push must not point off-lane before sign-ups start
  -- producing notifications. push_on_notification POSTs to push_config.function_url;
  -- it must be NULL or staging's own project. Only the host is ever printed.
  IF to_regclass('public.push_config') IS NOT NULL THEN
    FOR r IN
      SELECT coalesce(substring(pc.function_url FROM '^[a-zA-Z]+://([^/?#]+)'), '(unparseable)') AS host
        FROM public.push_config pc
       WHERE pc.function_url IS NOT NULL
         AND left(pc.function_url, length('https://fpszggreishhuvdpkmdr.supabase.co/'))
             IS DISTINCT FROM 'https://fpszggreishhuvdpkmdr.supabase.co/'
    LOOP
      _bad := _bad || E'\n  PRE-005 public.push_config.function_url points at host ' || r.host
                   || ' — repoint staging push to https://fpszggreishhuvdpkmdr.supabase.co/ (or NULL) first';
    END LOOP;
  END IF;

  IF _bad <> '' THEN
    RAISE EXCEPTION 'AUTHTRG-0002-PRE: staging is not in the state this file was written for — nothing applied:%', _bad
    USING ERRCODE = 'raise_exception';
  END IF;
END
$preconditions$;

-- ── apply ─────────────────────────────────────────────────────────────────
DO $apply$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_trigger
                  WHERE tgrelid = 'auth.users'::regclass AND tgname = 'on_auth_user_created') THEN
    CREATE TRIGGER on_auth_user_created
      AFTER INSERT ON auth.users
      FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();
    RAISE NOTICE 'AUTHTRG-0002: on_auth_user_created created';
  ELSE
    RAISE NOTICE 'AUTHTRG-0002: on_auth_user_created already present with production''s definition; left as is';
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_trigger
                  WHERE tgrelid = 'auth.users'::regclass AND tgname = 'on_auth_user_login_sync') THEN
    CREATE TRIGGER on_auth_user_login_sync
      AFTER UPDATE ON auth.users
      FOR EACH ROW EXECUTE FUNCTION public.sync_oauth_on_login();
    RAISE NOTICE 'AUTHTRG-0002: on_auth_user_login_sync created';
  ELSE
    RAISE NOTICE 'AUTHTRG-0002: on_auth_user_login_sync already present with production''s definition; left as is';
  END IF;
END
$apply$;

-- ── postconditions ─────────────────────────────────────────────────────────
DO $postconditions$
DECLARE
  r    record;
  _bad text := '';
  _n   int;
BEGIN
  -- POST-001 · each trigger exists, reads exactly as production's, is enabled ('O'),
  -- and calls the public function production's calls.
  FOR r IN
    SELECT w.name, w.want_def, w.want_fn, t.oid AS tg_oid, pg_get_triggerdef(t.oid) AS got_def,
           t.tgenabled::text AS got_enabled, t.tgfoid
      FROM (VALUES
        ('on_auth_user_created',
         'CREATE TRIGGER on_auth_user_created AFTER INSERT ON auth.users FOR EACH ROW EXECUTE FUNCTION handle_new_user()',
         'public.handle_new_user()'::regprocedure),
        ('on_auth_user_login_sync',
         'CREATE TRIGGER on_auth_user_login_sync AFTER UPDATE ON auth.users FOR EACH ROW EXECUTE FUNCTION sync_oauth_on_login()',
         'public.sync_oauth_on_login()'::regprocedure)
      ) AS w(name, want_def, want_fn)
      LEFT JOIN pg_trigger t ON t.tgrelid = 'auth.users'::regclass AND t.tgname::text = w.name
  LOOP
    IF r.tg_oid IS NULL THEN
      _bad := _bad || E'\n  POST-001 ' || r.name || ' missing';
    ELSIF r.got_def IS DISTINCT FROM r.want_def OR r.got_enabled IS DISTINCT FROM 'O'
       OR r.tgfoid IS DISTINCT FROM r.want_fn::oid THEN
      _bad := _bad || E'\n  POST-001 ' || r.name || ' is ' || r.got_def || ' (enabled ' || r.got_enabled || ')';
    END IF;
  END LOOP;

  -- POST-002 · exactly two user triggers on auth.users, as on production.
  SELECT count(*) INTO _n FROM pg_trigger WHERE tgrelid = 'auth.users'::regclass AND NOT tgisinternal;
  IF _n <> 2 THEN
    _bad := _bad || E'\n  POST-002 ' || _n || ' user triggers on auth.users, expected 2';
  END IF;

  IF _bad <> '' THEN
    RAISE EXCEPTION 'AUTHTRG-0002-POST: post-state differs from the intended one:%', _bad USING ERRCODE = 'raise_exception';
  END IF;
  RAISE NOTICE 'AUTHTRG-0002: auth.users carries exactly production''s two user triggers (on_auth_user_created, on_auth_user_login_sync), both enabled';
END
$postconditions$;

COMMIT;
